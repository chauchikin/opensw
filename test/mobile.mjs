import { chromium, devices } from 'playwright';
import { spawn } from 'node:child_process';
const srv = spawn('python3', ['test/csp_server.py', '5194'], { stdio: 'ignore' });
await new Promise((r) => setTimeout(r, 800));
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1243/chrome-linux64/chrome' });
const ctx = await browser.newContext({ ...devices['iPhone 13'] });
const page = await ctx.newPage();
await page.goto('http://localhost:5194/');
await page.waitForTimeout(1500);
await page.screenshot({ path: 'test-out/m1.png' });
await page.tap('.math-display math-field');
await page.waitForTimeout(1200);
await page.screenshot({ path: 'test-out/m2.png' });
const desk = await browser.newPage({ viewport: { width: 1100, height: 800 } });
await desk.goto('http://localhost:5194/');
await desk.waitForTimeout(1500);
await desk.click('.math-inline math-field');
await desk.waitForTimeout(300);
await desk.screenshot({ path: 'test-out/d1.png' });
await browser.close(); srv.kill();
