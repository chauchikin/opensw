// window.sw: the commands for AI agents. Run: node test/api.mjs
import { chromium } from 'playwright';
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1243/chrome-linux64/chrome' });
const page = await b.newPage();
const errs = []; page.on('pageerror', (e) => errs.push(e.message));
await page.goto('http://localhost:4173/?lang=zh-TW'); await page.waitForTimeout(600);
let fails = 0;
const check = (name, ok, detail) => { if (!ok) fails++; console.log(ok ? 'ok  ' : 'FAIL', name, detail === undefined ? '' : JSON.stringify(detail).slice(0, 200)); };
const call = (cmd, args) => page.evaluate(([c, a]) => window.sw.call(c, a), [cmd, args]);

let r = await call('help');
check('help lists commands', r.ok && r.result.length >= 15, r.result.map((x) => x.name));
r = await call('set', { latex: '\\section{Intro}\nLet $x^2+1=0$.\n\n\\begin{theorem}Every $n$ is fine.\\end{theorem}\n\\[\\int_0^1 f\\,dx\\]' });
check('set', r.ok && r.result.blocks === 4, r);
r = await call('outline');
check('outline', r.ok && r.result[0].type === 'heading2' && r.result[2].type === 'env:theorem' && r.result[3].type === 'math_display', r.result);
r = await call('insert', { latex: 'New paragraph with $\\alpha$.', index: 0 });
check('insert after block 0', r.ok && r.result.at === 1, r);
r = await call('outline');
check('inserted text is block 1', r.result[1].text.startsWith('New paragraph'), r.result[1]);
r = await call('replaceBlock', { index: 1, latex: '\\subsection*{Changed}' });
r = await call('outline');
check('replaceBlock', r.result[1].type === 'heading3', r.result[1]);
r = await call('formulas');
check('formulas', r.ok && r.result.length === 3 && r.result[2].display, r.result);
r = await call('setFormula', { n: 0, latex: 'x^2-1=0' });
r = await call('formulas');
check('setFormula', r.result[0].latex === 'x^2-1=0', r.result[0]);
r = await call('replace', { find: 'fine', with: 'good' });
check('replace text', r.ok && r.result.replaced === 1, r);
r = await call('find', { text: 'good' });
check('find gives block', r.ok && r.result[0].block === 3, r);
r = await call('get', { format: 'latex' });
check('get latex', r.ok && r.result.includes('\\begin{theorem}') && r.result.includes('x^2-1=0'), r.result.slice(-300));
r = await call('get', { format: 'markdown' });
check('get markdown', r.ok && r.result.includes('**定理.**'), r.result);
// an empty input box left in a formula must not reach TeX (it stopped typesetting)
r = await call('setFormula', { n: 0, latex: '\\frac{\\placeholder{}}{\\placeholder{}}+1' });
r = await call('get', { format: 'latex' });
check('empty boxes leave no \\placeholder in LaTeX', r.ok && !r.result.includes('\\placeholder') && r.result.includes('\\frac{{}}{{}}+1'), r.result.slice(0, 400));
r = await call('get', { format: 'markdown' });
check('empty boxes leave no \\placeholder in Markdown', r.ok && !r.result.includes('\\placeholder'), r.result);
r = await call('setFormula', { n: 0, latex: 'x^2-1=0' });
r = await call('deleteBlock', { index: 1 });
check('deleteBlock', r.ok && r.result.blocks === 4, r);
r = await call('undo');
r = await call('info');
check('undo + info', r.ok && r.result.blocks === 5, r);
r = await call('nosuch');
check('unknown command is an error', !r.ok && r.error.includes('沒有這個指令'), r);
r = await call('replaceBlock', { index: 99, latex: 'x' });
check('bad index is an error', !r.ok && r.error.includes('沒有第 99 塊'), r);
r = await call('open', { path: '/x.sci' });
check('open needs the desktop app', !r.ok, r);
console.log('page errors', errs);
console.log(fails ? `${fails} FAILED` : 'all passed');
await b.close();
process.exit(fails ? 1 : 0);
