import { chromium } from 'playwright';
import { spawn } from 'node:child_process';
const srv = spawn('python3', ['test/csp_server.py', '5190'], { stdio: 'ignore' });
await new Promise((r) => setTimeout(r, 800));
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1243/chrome-linux64/chrome' });
const page = await browser.newPage({ viewport: { width: 1100, height: 800 } });
await page.goto('http://localhost:5190/');
await page.waitForTimeout(1000);
const w = () => page.evaluate(() => Math.round(document.querySelector('#page').getBoundingClientRect().width));
console.log('100%:', await w());
await page.selectOption('#zoom-select', '1.25');
console.log(await page.textContent('#status-zoom'), await w());
await page.click('.ProseMirror p');
await page.keyboard.press('Control+='); 
console.log('after Ctrl+=', await page.textContent('#status-zoom'));
await page.selectOption('#zoom-select', '1');
console.log('after choosing 100%', await page.textContent('#status-zoom'), await w());
await page.selectOption('#zoom-select', '1.75');
await page.click('.math-inline math-field');
await page.waitForTimeout(300);
await page.keyboard.type('+1');
await page.keyboard.press('Escape');
console.log('typing into a formula at', await page.textContent('#status-zoom'), '->', await page.evaluate(() => { let l; window.swEditor.state.doc.descendants((n) => { if (!l && n.type.name === 'math_inline') l = n.attrs.latex; }); return l; }));
await page.screenshot({ path: 'test-out/zoom.png' });
await page.reload(); await page.waitForTimeout(800);
console.log('remembered after reload:', await page.textContent('#status-zoom'));
await browser.close(); srv.kill();
